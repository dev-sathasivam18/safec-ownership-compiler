"""Stage 6: C code generation (only reached for programs that passed every check)."""
from .nodes import *


def cty(t):
    return {"int": "int", "void": "void", "own": "int *", "ptr": "int *"}[t]


def gen_expr(e):
    if isinstance(e, Num):
        return str(e.value)
    if isinstance(e, Var):
        return e.name
    if isinstance(e, Deref):
        return f"(*{e.target.name})"
    if isinstance(e, Unary):
        return f"({e.op}{gen_expr(e.operand)})"
    if isinstance(e, Binary):
        return f"({gen_expr(e.left)} {e.op} {gen_expr(e.right)})"
    if isinstance(e, Alloc):
        return f"(int *)malloc({gen_expr(e.size)})"
    if isinstance(e, Call):
        if e.name == "print":
            return f'printf("%d\\n", {gen_expr(e.args[0])})'
        return f"{e.name}({', '.join(gen_expr(a) for a in e.args)})"
    raise AssertionError(e)


def gen_stmt(s, ind):
    p = "    " * ind
    if isinstance(s, Block):
        out = [p + "{"]
        for x in s.stmts:
            out += gen_stmt(x, ind + 1)
        return out + [p + "}"]
    if isinstance(s, Decl):
        init = f" = {gen_expr(s.init)}" if s.init is not None else ""
        return [f"{p}{cty(s.vty)} {s.name}{init};"]
    if isinstance(s, Assign):
        return [f"{p}{s.name} = {gen_expr(s.value)};"]
    if isinstance(s, Store):
        return [f"{p}*{s.target.name} = {gen_expr(s.value)};"]
    if isinstance(s, Free):
        return [f"{p}free({s.target.name});"]
    if isinstance(s, ExprStmt):
        return [f"{p}{gen_expr(s.expr)};"]
    if isinstance(s, Return):
        return [f"{p}return{' ' + gen_expr(s.value) if s.value is not None else ''};"]
    if isinstance(s, If):
        out = [f"{p}if ({gen_expr(s.cond)})"] + gen_stmt(wrap(s.then), ind)
        if s.els:
            out += [f"{p}else"] + gen_stmt(wrap(s.els), ind)
        return out
    if isinstance(s, While):
        return [f"{p}while ({gen_expr(s.cond)})"] + gen_stmt(wrap(s.body), ind)
    raise AssertionError(s)


def wrap(s):
    return s if isinstance(s, Block) else Block(s.line, s.col, [s])


def generate(prog, source_name="<input>"):
    out = [f"/* Generated by SafeC from {source_name}. Ownership verified at compile time. */",
           "#include <stdio.h>", "#include <stdlib.h>", ""]
    sigs = []
    for f in prog.funcs:
        ps = ", ".join(f"{cty(p.pty)} {p.name}" for p in f.params) or "void"
        sigs.append(f"{cty(f.ret)} {f.name}({ps})")
    out += [s + ";" for s in sigs if not s.startswith("int main")]
    out.append("")
    for f, sig in zip(prog.funcs, sigs):
        out.append(sig)
        out += gen_stmt(f.body, 0)
        out.append("")
    return "\n".join(out)
